package Model;

public class Cliente {
    private int idcliente;
    private String nomecliente;
    private String cpfcliente;
    private String telcliente;
    private String emailcliente;
    private String endcliente;

    public int getIdcliente() { return idcliente; }
    public void setIdcliente(int idcliente) { this.idcliente = idcliente; }
    public String getNomecliente() { return nomecliente; }
    public void setNomecliente(String nomecliente) { this.nomecliente = nomecliente; }
    public String getCpfcliente() { return cpfcliente; }
    public void setCpfcliente(String cpfcliente) { this.cpfcliente = cpfcliente; }
    public String getTelcliente() { return telcliente; }
    public void setTelcliente(String telcliente) { this.telcliente = telcliente; }
    public String getEmailcliente() { return emailcliente; }
    public void setEmailcliente(String emailcliente) { this.emailcliente = emailcliente; }
    public String getEndcliente() { return endcliente; }
    public void setEndcliente(String endcliente) { this.endcliente = endcliente; }
}
