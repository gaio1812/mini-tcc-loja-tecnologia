    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Model.Cliente c = new Model.Cliente();
        c.setNomecliente(jTextField1.getText().trim());
        c.setCpfcliente(jTextField2.getText().trim());
        c.setTelcliente(jTextField3.getText().trim());
        c.setEmailcliente(jTextField4.getText().trim());
        c.setEndcliente(jTextField5.getText().trim());

        if (c.getNomecliente().isEmpty() || c.getCpfcliente().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Nome e CPF são obrigatórios.");
            return;
        }

        if (new Model.ConTBCLIENTE().Cadastrar(c)) {
            jTextField1.setText("");
            jTextField2.setText("");
            jTextField3.setText("");
            jTextField4.setText("");
            jTextField5.setText("");
        }
    }//GEN-LAST:event_jButton1ActionPerformed

