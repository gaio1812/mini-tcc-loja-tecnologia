CREATE TABLE IF NOT EXISTS TBAPPLOCK (
    id INTEGER NOT NULL PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS TBUSUARIO (
    idusuario INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nomeusuario VARCHAR(100) NOT NULL,
    emailusuario VARCHAR(100) NOT NULL UNIQUE,
    senhausuario VARCHAR(255) NOT NULL,
    tipousuario VARCHAR(20) NOT NULL DEFAULT 'FUNCIONARIO'
);
CREATE TABLE IF NOT EXISTS TBCLIENTE (
    idcliente INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nomecliente VARCHAR(100) NOT NULL,
    cpfcliente VARCHAR(14) NOT NULL UNIQUE,
    telcliente VARCHAR(15),
    emailcliente VARCHAR(100),
    endcliente VARCHAR(150)
);
CREATE TABLE IF NOT EXISTS TBPRODUTO (
    idprod INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nomeprod VARCHAR(50) NOT NULL,
    categprod VARCHAR(40),
    marcprod VARCHAR(40),
    qtdprod INTEGER NOT NULL CHECK (qtdprod >= 0),
    precoprod DECIMAL(10,2) NOT NULL CHECK (precoprod >= 0)
);
CREATE TABLE IF NOT EXISTS TBVENDA (
    idvenda INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,
    codcliente INTEGER NOT NULL,
    datavenda DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    formapagamento VARCHAR(30) NOT NULL,
    statusvenda VARCHAR(20) NOT NULL DEFAULT 'CONCLUIDA',
    valorvenda DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    FOREIGN KEY (codcliente) REFERENCES TBCLIENTE(idcliente)
);
CREATE TABLE IF NOT EXISTS TBITEMVENDA (
    iditem INTEGER NOT NULL AUTO_INCREMENT PRIMARY KEY,
    codvenda INTEGER NOT NULL,
    codprod INTEGER NOT NULL,
    qtditem INTEGER NOT NULL CHECK (qtditem > 0),
    valorunitario DECIMAL(10,2) NOT NULL CHECK (valorunitario >= 0),
    FOREIGN KEY (codvenda) REFERENCES TBVENDA(idvenda),
    FOREIGN KEY (codprod) REFERENCES TBPRODUTO(idprod)
);
